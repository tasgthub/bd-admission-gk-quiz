function populateSetDropdown() {
  const filteredSets = QUIZ_DATA.filter(
    (s) => state.category === "all" || s.category === state.category
  );
  setSelect.innerHTML = `<option value="all">সবগুলো মডেল টেস্ট (${filteredSets.length}টি)</option>`;
  filteredSets.forEach((s) => {
    const opt = document.createElement("option");
    opt.value = s.id;
    opt.textContent = s.setTitle;
    setSelect.appendChild(opt);
  });
  state.setId = "all";
}

function getFilteredQuestions() {
  const list = [];
  QUIZ_DATA.forEach((set) => {
    if (state.category !== "all" && set.category !== state.category) return;
    if (state.setId !== "all" && set.id !== state.setId) return;

    set.questions.forEach((item) => {
      if (state.onlyFlagged && !item.note) return;
      const term = state.search.trim().toLowerCase();
      if (term) {
        const hay = `${item.q} ${Object.values(item.options).join(" ")} ${item.note || ""}`.toLowerCase();
        if (!hay.includes(term)) return;
      }
      list.push({ ...item, setId: set.id, setTitle: set.setTitle });
    });
  });
  return list;
}

function render() {
  const items = getFilteredQuestions();
  document.getElementById("totalCount").textContent = items.length;
  document.getElementById("flaggedCount").textContent = items.filter((i) => i.note).length;

  let attempted = 0;
  let correct = 0;
  Object.entries(state.userAnswers).forEach(([key, chosen]) => {
    const [sId, qNo] = key.split(":");
    const set = QUIZ_DATA.find((s) => s.id === sId);
    const qObj = set?.questions.find((q) => String(q.no) === qNo);
    if (qObj && qObj.ans) {
      attempted++;
      if (chosen === qObj.ans) correct++;
    }
  });
  document.getElementById("scoreDisplay").textContent =
    state.mode === "quiz" ? `${correct} / ${attempted}` : "অনুশীলন মোড";

  if (!items.length) {
    questionsContainer.innerHTML = `<div class="q-card"><p>কোনো প্রশ্ন পাওয়া যায়নি। ফিল্টার পরিবর্তন করে আবার চেষ্টা করুন।</p></div>`;
    return;
  }

  questionsContainer.innerHTML = items
    .map((item) => {
      const uid = `${item.setId}:${item.no}`;
      const chosen = state.userAnswers[uid];
      const reveal = state.mode === "study" ? state.showAnswers : Boolean(chosen);

      const optionsHtml = ["A", "B", "C", "D"]
        .map((key) => {
          let cls = "option-btn";
          if (reveal) {
            if (item.ans === key) cls += " correct";
            else if (chosen === key && item.ans !== key) cls += " wrong";
          }
          return `
            <button class="${cls}" type="button" data-uid="${uid}" data-key="${key}">
              <span class="opt-key">${key}</span>
              <span>${item.options[key] || ""}</span>
            </button>
          `;
        })
        .join("");

      const noteHtml = item.note ? `<div class="verify-note">⚠️ ${item.note}</div>` : "";

      return `
        <article class="q-card ${item.note ? "has-flag" : ""}">
          <div class="q-meta">
            <span class="q-tag">${item.setTitle}</span>
            <span>প্রশ্ন নং: ${item.no}</span>
          </div>
          <h2 class="q-title">${item.no}. ${item.q}</h2>
          <div class="options-list">${optionsHtml}</div>
          ${noteHtml}
        </article>
      `;
    })
    .join("");
}

questionsContainer.addEventListener("click", (e) => {
  const btn = e.target.closest(".option-btn");
  if (!btn) return;
  state.userAnswers[btn.dataset.uid] = btn.dataset.key;
  render();
});

categorySelect.addEventListener("change", (e) => {
  state.category = e.target.value;
  populateSetDropdown();
  render();
});

setSelect.addEventListener("change", (e) => {
  state.setId = e.target.value;
  render();
});

searchInput.addEventListener("input", (e) => {
  state.search = e.target.value;
  render();
});

toggleAnswersBtn.addEventListener("click", () => {
  state.showAnswers = !state.showAnswers;
  toggleAnswersBtn.textContent = `সঠিক উত্তর হাইলাইট: ${state.showAnswers ? "চালু" : "বন্ধ"}`;
  render();
});

toggleFlaggedBtn.addEventListener("click", () => {
  state.onlyFlagged = !state.onlyFlagged;
  toggleFlaggedBtn.classList.toggle("active", state.onlyFlagged);
  render();
});

studyModeBtn.addEventListener("click", () => {
  state.mode = "study";
  studyModeBtn.classList.add("active");
  quizModeBtn.classList.remove("active");
  render();
});

quizModeBtn.addEventListener("click", () => {
  state.mode = "quiz";
  quizModeBtn.classList.add("active");
  studyModeBtn.classList.remove("active");
  render();
});

resetQuizBtn.addEventListener("click", () => {
  state.userAnswers = {};
  render();
});

populateSetDropdown();
render();
